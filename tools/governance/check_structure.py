#!/usr/bin/env python3
"""Validate repository layout against governance/structure.json.

The manifest is the single authoritative description of where files may live.
This checker validates the manifest itself, every file Git would commit, every
non-ignored directory on disk, and the generated .github/CODEOWNERS file.

Usage:
    python3 tools/governance/check_structure.py          # validate only
    python3 tools/governance/check_structure.py --write  # regenerate, then validate

Standard library only (Python 3.10+). Git is the only external command.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import posixpath
import re
import stat
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

MANIFEST_PATH = "governance/structure.json"
CODEOWNERS_PATH = ".github/CODEOWNERS"
LEGACY_LOCK_PATH = "governance/legacy-decisions.json"

FORBIDDEN_DIRECTORY_NAMES = frozenset(
    {"adr", "adrs", "decisions", "architecture-decisions", "design-docs"}
)
ARCH_FILE_PATTERN = re.compile(r"^ARCH-\d{4}")
OWNER_PATTERN = re.compile(
    r"^@[A-Za-z0-9](?:[A-Za-z0-9]|-(?=[A-Za-z0-9])){0,38}(?:/[A-Za-z0-9][A-Za-z0-9._-]*)?$"
)

TOP_LEVEL_KEYS = {"version", "default_owners", "canonical", "root_files", "directories"}
REQUIRED_TOP_LEVEL_KEYS = TOP_LEVEL_KEYS
CANONICAL_KEYS = {"architecture_records"}
ROOT_FILE_KEYS = {"path", "purpose", "required", "owners"}
DIRECTORY_KEYS = {
    "path", "purpose", "children", "owners", "readme", "status", "source", "legacy_decision_dirs"
}
CHILD_POLICIES = ("declared", "open")
STATUSES = ("active", "reserved")
SOURCE_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9-]*/[A-Za-z0-9._-]+$")

CODEOWNERS_HEADER = (
    "# Generated by tools/governance/check_structure.py from governance/structure.json.\n"
    "# Do not edit by hand. Regenerate with: python3 tools/governance/check.py --write\n"
)


@dataclass(frozen=True)
class RootFile:
    path: str
    purpose: str
    required: bool
    owners: tuple[str, ...]


@dataclass(frozen=True)
class Directory:
    path: str
    purpose: str
    children: str
    owners: tuple[str, ...]
    readme: bool
    status: str
    source: str | None
    legacy_decision_dirs: tuple[str, ...] = ()


@dataclass
class Manifest:
    version: int
    default_owners: tuple[str, ...]
    architecture_records: str
    root_files: dict[str, RootFile] = field(default_factory=dict)
    directories: dict[str, Directory] = field(default_factory=dict)


class ManifestError(Exception):
    """Raised with a list of messages when the manifest is invalid."""

    def __init__(self, errors: list[str]):
        super().__init__("\n".join(errors))
        self.errors = errors


# ---------------------------------------------------------------------------
# Manifest parsing


def _reject_duplicate_keys(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key {key!r}")
        result[key] = value
    return result


def normalized_relative_path(value: object) -> str | None:
    """Return the path if it is a clean repository-relative POSIX path."""
    if not isinstance(value, str) or not value:
        return None
    if "\\" in value or "\x00" in value or value.startswith("/") or value.endswith("/"):
        return None
    parts = value.split("/")
    if any(part in ("", ".", "..") for part in parts):
        return None
    if posixpath.normpath(value) != value:
        return None
    if parts[0] == ".git":
        return None
    return value


def _validate_owners(value: object, where: str, errors: list[str], allow_empty: bool) -> tuple[str, ...]:
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        errors.append(f"{where}: owners must be a list of strings")
        return ()
    if not value and not allow_empty:
        errors.append(f"{where}: owners must not be empty")
    for owner in value:
        if not OWNER_PATTERN.match(owner):
            errors.append(f"{where}: invalid owner handle {owner!r} (expected @user or @org/team)")
    if len(set(value)) != len(value):
        errors.append(f"{where}: duplicate owner handles")
    return tuple(value)


def _validate_purpose(value: object, where: str, errors: list[str]) -> str:
    if not isinstance(value, str) or not value.strip():
        errors.append(f"{where}: purpose must be a non-empty string")
        return ""
    return value


def parse_manifest(text: str) -> Manifest:
    errors: list[str] = []
    try:
        data = json.loads(text, object_pairs_hook=_reject_duplicate_keys)
    except ValueError as exc:
        raise ManifestError([f"{MANIFEST_PATH}: invalid JSON: {exc}"]) from None
    if not isinstance(data, dict):
        raise ManifestError([f"{MANIFEST_PATH}: top level must be an object"])

    unknown = set(data) - TOP_LEVEL_KEYS
    missing = REQUIRED_TOP_LEVEL_KEYS - set(data)
    if unknown:
        errors.append(f"manifest: unknown keys {sorted(unknown)}")
    if missing:
        raise ManifestError(errors + [f"manifest: missing keys {sorted(missing)}"])

    version = data["version"]
    if version != 1 or isinstance(version, bool):
        errors.append("manifest: version must be 1")

    default_owners = _validate_owners(data["default_owners"], "default_owners", errors, allow_empty=False)

    canonical = data["canonical"]
    records_dir = ""
    if not isinstance(canonical, dict):
        errors.append("canonical: must be an object")
    else:
        unknown = set(canonical) - CANONICAL_KEYS
        if unknown:
            errors.append(f"canonical: unknown keys {sorted(unknown)}")
        if "architecture_records" not in canonical:
            errors.append("canonical: missing architecture_records")
        else:
            records_dir = normalized_relative_path(canonical["architecture_records"]) or ""
            if not records_dir:
                errors.append("canonical.architecture_records: must be a normalized relative path")

    manifest = Manifest(
        version=1, default_owners=default_owners, architecture_records=records_dir
    )

    root_files = data["root_files"]
    if not isinstance(root_files, list):
        errors.append("root_files: must be a list")
        root_files = []
    for index, entry in enumerate(root_files):
        where = f"root_files[{index}]"
        if not isinstance(entry, dict):
            errors.append(f"{where}: must be an object")
            continue
        unknown = set(entry) - ROOT_FILE_KEYS
        if unknown:
            errors.append(f"{where}: unknown keys {sorted(unknown)}")
        path = normalized_relative_path(entry.get("path"))
        if path is None:
            errors.append(f"{where}: path must be a normalized relative path")
            continue
        where = f"root_files[{path}]"
        if "/" in path:
            errors.append(f"{where}: root files must be directly in the repository root")
            continue
        if path in manifest.root_files:
            errors.append(f"{where}: duplicate root file")
            continue
        purpose = _validate_purpose(entry.get("purpose"), where, errors)
        required = entry.get("required", False)
        if not isinstance(required, bool):
            errors.append(f"{where}: required must be a boolean")
            required = False
        owners = ()
        if "owners" in entry:
            owners = _validate_owners(entry["owners"], where, errors, allow_empty=False)
        manifest.root_files[path] = RootFile(path, purpose, required, owners)

    directories = data["directories"]
    if not isinstance(directories, list):
        errors.append("directories: must be a list")
        directories = []
    for index, entry in enumerate(directories):
        where = f"directories[{index}]"
        if not isinstance(entry, dict):
            errors.append(f"{where}: must be an object")
            continue
        unknown = set(entry) - DIRECTORY_KEYS
        if unknown:
            errors.append(f"{where}: unknown keys {sorted(unknown)}")
        path = normalized_relative_path(entry.get("path"))
        if path is None:
            errors.append(f"{where}: path must be a normalized relative path")
            continue
        where = f"directories[{path}]"
        if path in manifest.directories:
            errors.append(f"{where}: duplicate directory")
            continue
        if path in manifest.root_files:
            errors.append(f"{where}: path is also declared as a root file")
        forbidden = [part for part in path.split("/") if part.lower() in FORBIDDEN_DIRECTORY_NAMES]
        if forbidden:
            errors.append(f"{where}: forbidden decision-directory name {forbidden[0]!r}")
        parent = posixpath.dirname(path)
        if parent:
            parent_entry = manifest.directories.get(parent)
            if parent_entry is None:
                errors.append(f"{where}: parent {parent!r} must be declared before its children")
            elif parent_entry.children != "declared":
                errors.append(
                    f"{where}: parent {parent!r} has children policy "
                    f"{parent_entry.children!r}; only 'declared' parents may declare children"
                )
        purpose = _validate_purpose(entry.get("purpose"), where, errors)
        children = entry.get("children")
        if children not in CHILD_POLICIES:
            errors.append(f"{where}: children must be one of {list(CHILD_POLICIES)}")
            children = "declared"
        status = entry.get("status", "active")
        if status not in STATUSES:
            errors.append(f"{where}: status must be one of {list(STATUSES)}")
            status = "active"
        readme = entry.get("readme", True)
        if not isinstance(readme, bool):
            errors.append(f"{where}: readme must be a boolean")
            readme = True
        owners = ()
        if "owners" in entry:
            owners = _validate_owners(entry["owners"], where, errors, allow_empty=False)
        source = entry.get("source")
        if source is not None:
            if not isinstance(source, str) or not SOURCE_PATTERN.match(source):
                errors.append(f"{where}: source must be an owner/repository name")
                source = None
            elif status != "reserved":
                errors.append(f"{where}: source is only meaningful for reserved directories")
            elif not readme:
                errors.append(f"{where}: reserved directories with a source must keep a README")
        legacy: tuple[str, ...] = ()
        if "legacy_decision_dirs" in entry:
            raw = entry["legacy_decision_dirs"]
            if not isinstance(raw, list) or not all(
                normalized_relative_path(item) for item in raw
            ):
                errors.append(f"{where}: legacy_decision_dirs must be a list of relative paths")
            elif children != "open":
                errors.append(f"{where}: legacy_decision_dirs requires an open directory")
            else:
                legacy = tuple(f"{path}/{item}" for item in raw)
        manifest.directories[path] = Directory(
            path, purpose, children, owners, readme, status, source, legacy
        )

    if records_dir and records_dir not in manifest.directories:
        errors.append(
            f"canonical.architecture_records: {records_dir!r} must be a declared directory"
        )
    if posixpath.dirname(CODEOWNERS_PATH) not in manifest.directories:
        errors.append(f"manifest: {posixpath.dirname(CODEOWNERS_PATH)!r} must be declared")
    if MANIFEST_PATH.split("/")[0] not in manifest.directories:
        errors.append(f"manifest: {MANIFEST_PATH.split('/')[0]!r} must be declared")

    if errors:
        raise ManifestError(errors)
    return manifest


def load_manifest(root: Path) -> Manifest:
    path = root / MANIFEST_PATH
    if path.is_symlink() or not path.is_file():
        raise ManifestError([f"{MANIFEST_PATH}: missing or not a regular file"])
    return parse_manifest(path.read_text(encoding="utf-8"))


# ---------------------------------------------------------------------------
# CODEOWNERS


def render_codeowners(manifest: Manifest) -> str:
    lines = [CODEOWNERS_HEADER, f"* {' '.join(manifest.default_owners)}\n"]
    owned_files = [entry for entry in manifest.root_files.values() if entry.owners]
    if owned_files:
        lines.append("\n# Root files\n")
        for entry in sorted(owned_files, key=lambda item: item.path):
            lines.append(f"/{entry.path} {' '.join(entry.owners)}\n")
    owned_dirs = [entry for entry in manifest.directories.values() if entry.owners]
    if owned_dirs:
        lines.append("\n# Directories (parents precede children; the last match wins)\n")
        for entry in sorted(owned_dirs, key=lambda item: item.path.split("/")):
            lines.append(f"/{entry.path}/ {' '.join(entry.owners)}\n")
    return "".join(lines)


# ---------------------------------------------------------------------------
# Repository enumeration


def _git(root: Path, *args: str, stdin: bytes | None = None) -> bytes:
    result = subprocess.run(
        ["git", "-C", str(root), *args],
        input=stdin,
        capture_output=True,
        check=False,
    )
    if result.returncode not in (0, 1):
        raise RuntimeError(
            f"git {' '.join(args)} failed: {result.stderr.decode('utf-8', 'replace').strip()}"
        )
    return result.stdout


def candidate_files(root: Path) -> list[str]:
    """Every path Git would commit: tracked plus untracked, non-ignored files."""
    output = _git(root, "ls-files", "-z", "--cached", "--others", "--exclude-standard")
    paths = {item.decode("utf-8", "surrogateescape") for item in output.split(b"\0") if item}
    return sorted(paths)


def _ignored(root: Path, paths: list[str]) -> set[str]:
    if not paths:
        return set()
    output = _git(root, "check-ignore", "-z", "--stdin", stdin=b"\0".join(
        p.encode("utf-8", "surrogateescape") for p in paths
    ) + b"\0")
    return {item.decode("utf-8", "surrogateescape") for item in output.split(b"\0") if item}


def candidate_directories(root: Path) -> tuple[list[str], list[str]]:
    """Non-ignored directories on disk, including empty ones.

    Returns (directories, symlinked_directories). Walks breadth first so whole
    ignored subtrees are pruned with one git call per depth level.
    """
    found: list[str] = []
    symlinks: list[str] = []
    level = [""]
    while level:
        children: list[str] = []
        for parent in level:
            base = root / parent if parent else root
            try:
                entries = sorted(os.scandir(base), key=lambda e: e.name)
            except OSError:
                continue
            for entry in entries:
                if entry.name == ".git":
                    continue
                rel = f"{parent}/{entry.name}" if parent else entry.name
                if entry.is_symlink():
                    symlinks.append(rel)
                elif entry.is_dir(follow_symlinks=False):
                    children.append(rel)
        ignored = _ignored(root, [f"{c}/" for c in children])
        level = [c for c in children if f"{c}/" not in ignored and c not in ignored]
        found.extend(level)
    ignored_links = _ignored(root, symlinks)
    return sorted(found), sorted(s for s in symlinks if s not in ignored_links)


# ---------------------------------------------------------------------------
# Validation


def _deepest_declared(manifest: Manifest, directory: str) -> str | None:
    current = directory
    while current:
        if current in manifest.directories:
            return current
        current = posixpath.dirname(current)
    return None


def _check_directory_location(manifest: Manifest, directory: str) -> str | None:
    """Return an error message if a directory is not authorized, else None."""
    if directory in manifest.directories:
        return None
    anchor = _deepest_declared(manifest, directory)
    if anchor is None:
        top = directory.split("/")[0]
        return f"{top}/: undeclared top-level directory (declare it in {MANIFEST_PATH})"
    entry = manifest.directories[anchor]
    first = anchor + "/" + directory[len(anchor) + 1 :].split("/")[0]
    if entry.children != "open":
        return (
            f"{first}/: undeclared directory under {anchor}/, whose children "
            f"must be declared in {MANIFEST_PATH}"
        )
    if entry.status == "reserved":
        return (
            f"{first}/: {anchor}/ is reserved and has no imported code; "
            f"mark it active in {MANIFEST_PATH} as part of an authorized import"
        )
    return None


def _check_file_location(manifest: Manifest, path: str) -> str | None:
    if "/" not in path:
        if path not in manifest.root_files:
            return f"{path}: undeclared root file (declare it in {MANIFEST_PATH} root_files)"
        return None
    directory = posixpath.dirname(path)
    error = _check_directory_location(manifest, directory)
    if error:
        return f"{path}: in {error}"
    anchor = _deepest_declared(manifest, directory)
    if manifest.directories[anchor].status == "reserved" and path != f"{anchor}/README.md":
        return (
            f"{path}: {anchor}/ is reserved and may contain only README.md until an "
            f"authorized import marks it active"
        )
    return None


def _legacy_decision_dir(manifest: Manifest, directory: str) -> bool:
    """True if a forbidden-named directory is a declared, pre-consolidation component
    decision directory (non-authoritative history imported with its component)."""
    return any(
        directory == legacy or directory.startswith(legacy + "/")
        for entry in manifest.directories.values()
        for legacy in entry.legacy_decision_dirs
    )


def _legacy_decision_files(manifest: Manifest, files: list[str]) -> list[str]:
    return [
        path
        for path in files
        if any(
            path.startswith(legacy + "/")
            for entry in manifest.directories.values()
            for legacy in entry.legacy_decision_dirs
        )
    ]


def validate_legacy_lock(root: Path, manifest: Manifest, files: list[str]) -> list[str]:
    """Legacy decision directories are frozen: every file in them must match
    governance/legacy-decisions.json byte for byte, and every locked file must exist.
    The lock is reviewed data, not a generated file; --write never changes it."""
    present = _legacy_decision_files(manifest, files)
    lock_file = root / LEGACY_LOCK_PATH
    if not lock_file.is_file() or lock_file.is_symlink():
        if present:
            return [f"{LEGACY_LOCK_PATH}: missing; legacy decision directories must be locked"]
        return []
    try:
        lock = json.loads(lock_file.read_text(encoding="utf-8"))
        locked = lock["files"]
        if not isinstance(locked, dict) or not all(
            isinstance(k, str) and isinstance(v, str) for k, v in locked.items()
        ):
            raise ValueError
    except (ValueError, KeyError, TypeError):
        return [f"{LEGACY_LOCK_PATH}: must be a JSON object with a files map of path to sha256"]

    errors: list[str] = []
    for path in present:
        digest = hashlib.sha256((root / path).read_bytes()).hexdigest()
        if path not in locked:
            errors.append(
                f"{path}: legacy decision directories are frozen; architecture records "
                f"belong in {manifest.architecture_records}/"
            )
        elif locked[path] != digest:
            errors.append(f"{path}: legacy decision record changed; it is frozen")
    present_set = set(present)
    for path in locked:
        if path not in present_set:
            errors.append(f"{path}: locked legacy decision record is missing")
    return errors


def _inside_root(root: Path, rel: str) -> bool:
    try:
        resolved = (root / rel).resolve()
        resolved.relative_to(root.resolve())
    except (OSError, ValueError):
        return False
    return True


def validate(root: Path, manifest: Manifest) -> list[str]:
    errors: list[str] = []
    files = candidate_files(root)
    directories, dir_symlinks = candidate_directories(root)

    for link in dir_symlinks:
        errors.append(f"{link}: symbolic links are not allowed in the governed tree")

    records_dir = manifest.architecture_records
    seen_dirs: set[str] = set()
    for path in files:
        if normalized_relative_path(path) is None:
            errors.append(f"{path!r}: path is not a normalized repository-relative path")
            continue
        full = root / path
        try:
            mode = os.lstat(full).st_mode
        except FileNotFoundError:
            mode = None
        if mode is not None and stat.S_ISLNK(mode):
            errors.append(f"{path}: symbolic links are not allowed in the governed tree")
            continue
        if not _inside_root(root, path):
            errors.append(f"{path}: resolves outside the repository")
            continue
        parts = path.split("/")
        for index, part in enumerate(parts[:-1]):
            if part.lower() in FORBIDDEN_DIRECTORY_NAMES and not _legacy_decision_dir(
                manifest, "/".join(parts[: index + 1])
            ):
                errors.append(
                    f"{path}: forbidden decision-directory name {part!r}; architecture "
                    f"records belong in {records_dir}/"
                )
                break
        error = _check_file_location(manifest, path)
        if error:
            errors.append(error)
        name = parts[-1]
        if ARCH_FILE_PATTERN.match(name) and posixpath.dirname(path) != records_dir:
            errors.append(
                f"{path}: architecture records must live directly in {records_dir}/"
            )
        current = posixpath.dirname(path)
        while current:
            seen_dirs.add(current)
            current = posixpath.dirname(current)

    for directory in directories:
        name = posixpath.basename(directory)
        if name.lower() in FORBIDDEN_DIRECTORY_NAMES and not _legacy_decision_dir(
            manifest, directory
        ):
            errors.append(
                f"{directory}/: forbidden decision-directory name {name!r}; architecture "
                f"records belong in {records_dir}/"
            )
            continue
        if directory in seen_dirs:
            continue  # its files were already checked
        error = _check_directory_location(manifest, directory)
        if error:
            errors.append(error)
        if ARCH_FILE_PATTERN.match(name):
            errors.append(f"{directory}/: ARCH-NNNN names are reserved for record files")

    file_set = set(files)
    for entry in manifest.root_files.values():
        if entry.required and entry.path not in file_set:
            errors.append(f"{entry.path}: required root file is missing")
    for entry in manifest.directories.values():
        if entry.readme:
            readme = f"{entry.path}/README.md"
            if readme not in file_set:
                errors.append(f"{readme}: required directory README is missing")
            elif entry.source:
                text = (root / readme).read_text(encoding="utf-8", errors="replace")
                if entry.source not in text:
                    errors.append(
                        f"{readme}: reserved directory README must name its intended "
                        f"source repository {entry.source}"
                    )

    errors.extend(validate_legacy_lock(root, manifest, files))

    expected = render_codeowners(manifest)
    codeowners = root / CODEOWNERS_PATH
    if codeowners.is_symlink() or not codeowners.is_file():
        errors.append(f"{CODEOWNERS_PATH}: missing; run python3 tools/governance/check.py --write")
    elif codeowners.read_text(encoding="utf-8") != expected:
        errors.append(f"{CODEOWNERS_PATH}: stale; run python3 tools/governance/check.py --write")

    return sorted(set(errors))


def write_generated(root: Path, manifest: Manifest) -> list[str]:
    """Write generated outputs. Returns the repository paths that changed."""
    target = root / CODEOWNERS_PATH
    expected = render_codeowners(manifest)
    if target.is_symlink():
        raise ManifestError([f"{CODEOWNERS_PATH}: refusing to write through a symbolic link"])
    if target.is_file() and target.read_text(encoding="utf-8") == expected:
        return []
    target.parent.mkdir(parents=True, exist_ok=True)
    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(expected)
    return [CODEOWNERS_PATH]


def run(root: Path, write: bool = False) -> list[str]:
    """Validate (optionally regenerating first). Returns a list of error messages."""
    try:
        manifest = load_manifest(root)
        if write:
            write_generated(root, manifest)
        return validate(root, manifest)
    except ManifestError as exc:
        return list(exc.errors)
    except RuntimeError as exc:
        return [str(exc)]


def repository_root() -> Path:
    return Path(__file__).resolve().parents[2]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="regenerate CODEOWNERS before validating")
    parser.add_argument("--root", type=Path, default=None, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    root = args.root or repository_root()
    errors = run(root, write=args.write)
    if errors:
        print("structure: FAILED", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1
    print("structure: ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
